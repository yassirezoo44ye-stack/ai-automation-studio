@router.get("/api/conversations")
async def list_conversations(
    request: Request,
    project_id: str | None = None,
    q: str | None = None,
    archived: bool = False,
    limit: int = 100,
):
    """List the caller's conversations, newest first.

    ``q`` matches the title or any message content. ``archived=true`` lists
    archived conversations instead of active ones.
    """
    limit = max(1, min(limit, 200))
    where = ["p.user_id=$1", "c.archived_at IS NOT NULL" if archived else "c.archived_at IS NULL"]
    args: list = []
    async with get_pool().acquire() as conn:
        uid = await owner_user_id(conn, request)
        args.append(uid)
        if project_id:
            pid = await resolve_project_id(conn, project_id, uid)
            args.append(pid)
            where.append(f"c.project_id=${len(args)}")
        if q and q.strip():
            args.append(f"%{q.strip()}%")
            n = len(args)
            where.append(
                f"(c.title ILIKE ${n} OR EXISTS (SELECT 1 FROM messages m "
                f"WHERE m.conversation_id=c.id AND m.content ILIKE ${n}))"
            )
        args.append(limit)
        rows = await conn.fetch(
            f"SELECT {_CONV_COLS} FROM conversations c JOIN projects p ON c.project_id=p.id "
            f"WHERE {' AND '.join(where)} ORDER BY c.updated_at DESC LIMIT ${len(args)}",
            *args,
        )
    return [_conv_out(r) for r in rows]


@router.get("/api/conversations/{conv_id}")
async def get_conversation(conv_id: str, request: Request):
    """Metadata for one conversation — used to restore the active chat after
    a reload (and to discover which project it belongs to)."""
    cid = _conv_uuid(conv_id)
    async with get_pool().acquire() as conn:
        uid = await owner_user_id(conn, request)
        row = await conn.fetchrow(
            f"SELECT {_CONV_COLS} FROM conversations c JOIN projects p ON c.project_id=p.id "
            "WHERE c.id=$1 AND p.user_id=$2",
            cid, uid,
        )
    if not row:
        raise HTTPException(404, "Conversation not found")
    return _conv_out(row)


@router.patch("/api/conversations/{conv_id}")
async def update_conversation(conv_id: str, body: ConversationUpdate, request: Request):
    """Rename and/or archive/unarchive a conversation the caller owns."""
    cid = _conv_uuid(conv_id)
    if body.title is None and body.archived is None:
        raise HTTPException(422, "Nothing to update")
    title = " ".join(body.title.split()) if body.title is not None else None
    if title is not None and not title:
        raise HTTPException(422, "Title cannot be blank")
    async with get_pool().acquire() as conn:
        uid = await owner_user_id(conn, request)
        row = await conn.fetchrow(
            "UPDATE conversations c SET "
            "  title = COALESCE($3, c.title), "
            "  archived_at = CASE WHEN $4::boolean IS NULL THEN c.archived_at "
            "                     WHEN $4 THEN COALESCE(c.archived_at, NOW()) ELSE NULL END "
            "FROM projects p WHERE c.project_id=p.id AND c.id=$1 AND p.user_id=$2 "
            f"RETURNING {_CONV_COLS}",
            cid, uid, title, body.archived,
        )
    if not row:
        raise HTTPException(404, "Conversation not found")
    return _conv_out(row)


@router.get("/api/conversations/{conv_id}/messages")
async def get_messages(conv_id: str, request: Request):
    cid = _conv_uuid(conv_id)
    async with get_pool().acquire() as conn:
        uid = await owner_user_id(conn, request)
        owned = await conn.fetchval(_OWNED_CONV_SQL, cid, uid)
        if not owned:
            raise HTTPException(404, "Conversation not found")
        rows = await conn.fetch(
            "SELECT id, role, content, status, client_request_id, created_at FROM messages "
            "WHERE conversation_id=$1 ORDER BY created_at",
            cid,
        )
    return [{"id": str(r["id"]), "role": r["role"], "content": r["content"],
             "status": r["status"],
             "client_request_id": str(r["client_request_id"]) if r["client_request_id"] else None,
             "created_at": r["created_at"].isoformat()} for r in rows]


@router.delete("/api/conversations/{conv_id}")
async def delete_conversation(conv_id: str, request: Request):
    cid = _conv_uuid(conv_id)
    async with get_pool().acquire() as conn:
        uid = await owner_user_id(conn, request)
        result = await conn.execute(
            "DELETE FROM conversations c USING projects p "
            "WHERE c.project_id=p.id AND c.id=$1 AND p.user_id=$2",
            cid, uid,
        )
    if result == "DELETE 0":
        raise HTTPException(404, "Conversation not found")
    return {"message": "Deleted"}


@router.get("/api/search")
async def search(q: str, request: Request, project_id: str | None = None):
    if not q or len(q) < 2:
        return {"conversations": [], "messages": []}
    async with get_pool().acquire() as conn:
        uid = await owner_user_id(conn, request)
        conv_rows = await conn.fetch(
            "SELECT c.id, c.title, c.updated_at FROM conversations c "
            "JOIN projects p ON c.project_id=p.id "
            "WHERE p.user_id=$1 AND c.title ILIKE $2 ORDER BY c.updated_at DESC LIMIT 10",
            uid, f"%{q}%",
        )
        msg_rows = await conn.fetch(
            "SELECT m.id, m.content, m.role, m.conversation_id, c.title "
            "FROM messages m JOIN conversations c ON m.conversation_id=c.id "
            "JOIN projects p ON c.project_id=p.id "
            "WHERE p.user_id=$1 AND m.content ILIKE $2 ORDER BY m.created_at DESC LIMIT 20",
            uid, f"%{q}%",
        )
    return {
        "conversations": [{"id": str(r["id"]), "title": r["title"],
                           "updated_at": r["updated_at"].isoformat()} for r in conv_rows],
        "messages": [{"id": str(r["id"]), "content": r["content"][:200], "role": r["role"],
                      "conversation_id": str(r["conversation_id"]), "conv_title": r["title"]}
                     for r in msg_rows],
    }


