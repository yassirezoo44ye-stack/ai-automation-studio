# Message status values stored in messages.status.
#   complete — a finished user message or a fully streamed assistant reply
#   partial  — an assistant reply cut off (provider error or disconnect);
#              the text that did stream is kept and shown as incomplete
#   failed   — an assistant reply that produced no text at all
STATUS_COMPLETE = "complete"
STATUS_PARTIAL = "partial"
STATUS_FAILED = "failed"

_OWNED_CONV_SQL = (
    "SELECT 1 FROM conversations c JOIN projects p ON c.project_id=p.id "
    "WHERE c.id=$1 AND p.user_id=$2"
)


class RunRequest(BaseModel):
    project_id: str
    # Length limits are enforced by app.core.chat_limits.validate_prompt so
    # an oversized prompt gets a structured, explainable 413 instead of a
    # bare pydantic 422 — and so the UI and server share one limit.
    prompt: str
    conversation_id: str | None = None
    # Text to store/display in place of `prompt` when the caller injects
    # invisible context into `prompt` (e.g. "[Context: …]\n\nuser message").
    # Storage (title, message content, usage log) uses this value when set;
    # the model always receives the full `prompt`.
    display_text: str | None = None
    # Stable id generated by the client once per *logical* send and reused on
    # every retry of that send. Makes the send idempotent: a retry never
    # stores a second user message, and a retry after a completed reply
    # replays the saved reply instead of calling the model (and paying) again.
    client_request_id: str | None = None


class ConversationCreate(BaseModel):
    project_id: str
    title: str | None = "New conversation"


class ConversationUpdate(BaseModel):
    title: str | None = Field(None, min_length=1, max_length=200)
    archived: bool | None = None


def _sse(payload: dict) -> str:
    return f"data: {json.dumps(payload, ensure_ascii=False)}\n\n"


def _conv_uuid(conv_id: str) -> uuid.UUID:
    """Parse a path conversation id; malformed ids are 'not found', not a 500."""
    try:
        return uuid.UUID(conv_id)
    except (ValueError, TypeError):
        raise HTTPException(404, "Conversation not found") from None


def _title_from(text: str) -> str:
    one_line = " ".join(text.split())
    return one_line[:60] + ("…" if len(one_line) > 60 else "")


def _history_rows_to_messages(rows) -> list[dict]:
    """Build model history from stored rows, skipping replies that failed
    with no text (they carry nothing for the model to continue from)."""
    out: list[dict] = []
    for r in rows:
        status = r.get("status") if hasattr(r, "get") else None
        if r["role"] == "assistant" and status == STATUS_FAILED:
            continue
        out.append({"role": r["role"], "content": r["content"]})
    return out


async def _save_assistant(conv_id: uuid.UUID, req_id: uuid.UUID | None,
                          content: str, status: str) -> None:
    """Persist the assistant reply. With a request id this is an upsert that
    never overwrites an already-complete reply (a concurrent retry may have
    finished first)."""
    async with get_pool().acquire() as conn:
        if req_id is None:
            await conn.execute(
                "INSERT INTO messages (conversation_id, role, content, status) "
                "VALUES ($1, 'assistant', $2, $3)",
                conv_id, content, status,
            )
        else:
            await conn.execute(
                "INSERT INTO messages (conversation_id, role, content, status, client_request_id) "
                "VALUES ($1, 'assistant', $2, $3, $4) "
                "ON CONFLICT (client_request_id, role) WHERE client_request_id IS NOT NULL "
                "DO UPDATE SET content=EXCLUDED.content, status=EXCLUDED.status, created_at=NOW() "
                "WHERE messages.status <> 'complete'",
                conv_id, content, status, req_id,
            )
        await conn.execute("UPDATE conversations SET updated_at=NOW() WHERE id=$1", conv_id)


