@router.post("/api/run/stream")
async def run_stream(req: RunRequest, request: Request):
    from app.core.reliability import get_bulkhead

    # Validate before any quota/rate accounting or DB write, so a rejected
    # prompt costs nothing and the client still holds the full draft.
    validate_prompt(req.prompt)
    if req.display_text is not None:
        validate_prompt(req.display_text, field="display_text")
    req_id: uuid.UUID | None = None
    if req.client_request_id:
        try:
            req_id = uuid.UUID(req.client_request_id)
        except ValueError:
            raise HTTPException(400, "Invalid client_request_id") from None

    bulkhead = get_bulkhead("ai", 32)
    ai_rate_limit(request)
    org_id = await check_org_quota(request)

    history: list[dict] = []
    conv_id: uuid.UUID | None = None
    user_msg_id: uuid.UUID | None = None
    replay_text: str | None = None
    is_retry = False

    # Text for storage and display — stripped of any invisible context the
    # caller injects into `prompt`. The model always receives the full
    # `prompt`; only DB rows and the title use this value.
    _user_text = req.display_text or req.prompt

    async with get_pool().acquire() as conn:
        uid = await owner_user_id(conn, request)

        # ── Retry of an earlier send (same client_request_id) ──────────
        existing = None
        if req_id is not None:
            existing = await conn.fetchrow(
                "SELECT m.id, m.conversation_id, m.created_at FROM messages m "
                "JOIN conversations c ON m.conversation_id=c.id "
                "JOIN projects p ON c.project_id=p.id "
                "WHERE m.client_request_id=$1 AND m.role='user' AND p.user_id=$2",
                req_id, uid,
            )
            if existing is None and await conn.fetchval(
                "SELECT 1 FROM messages WHERE client_request_id=$1", req_id,
            ):
                # Id is taken by another user's message. Don't reveal anything.
                raise HTTPException(409, "client_request_id already used")

        if existing is not None:
            is_retry = True
            conv_id = existing["conversation_id"]
            user_msg_id = existing["id"]
            if req.conversation_id and req.conversation_id != str(conv_id):
                raise HTTPException(409, "client_request_id belongs to a different conversation")
            prior = await conn.fetchrow(
                "SELECT content, status FROM messages "
                "WHERE client_request_id=$1 AND role='assistant'",
                req_id,
            )
            if prior is not None and prior["status"] == STATUS_COMPLETE:
                replay_text = prior["content"]
            else:
                rows = await conn.fetch(
                    "SELECT role, content, status FROM messages "
                    "WHERE conversation_id=$1 AND created_at < $2 ORDER BY created_at",
                    conv_id, existing["created_at"],
                )
                history = _history_rows_to_messages(rows)

        # ── First attempt ──────────────────────────────────────────────
        else:
            if req.conversation_id:
                try:
                    conv_id = uuid.UUID(req.conversation_id)
                except ValueError:
                    raise HTTPException(400, "Invalid conversation_id") from None
                owned = await conn.fetchval(_OWNED_CONV_SQL, conv_id, uid)
                if not owned:
                    raise HTTPException(404, "Conversation not found")
                rows = await conn.fetch(
                    "SELECT role, content, status FROM messages WHERE conversation_id=$1 ORDER BY created_at",
                    conv_id,
                )
                history = _history_rows_to_messages(rows)
            else:
                pid = await resolve_project_id(conn, req.project_id, uid)
                conv_id = await conn.fetchval(
                    "INSERT INTO conversations (project_id, title) VALUES ($1, $2) RETURNING id",
                    pid, _title_from(_user_text),
                )

            if req_id is None:
                # Legacy clients without a request id: unchanged behaviour.
                await conn.execute(
                    "INSERT INTO messages (conversation_id, role, content) VALUES ($1, 'user', $2)",
                    conv_id, _user_text,
                )
            else:
                user_msg_id = await conn.fetchval(
                    "INSERT INTO messages (conversation_id, role, content, client_request_id) "
                    "VALUES ($1, 'user', $2, $3) "
                    "ON CONFLICT (client_request_id, role) WHERE client_request_id IS NOT NULL "
                    "DO NOTHING RETURNING id",
                    conv_id, _user_text, req_id,
                )
                if user_msg_id is None:
                    # Two identical sends raced; the other one owns this turn.
                    raise HTTPException(409, "This message is already being sent")
            await conn.execute("UPDATE conversations SET updated_at=NOW() WHERE id=$1", conv_id)
            # Logged here (message saved) rather than only on AI success, so a
            # failed AI call still appears in Recent Activity. Preview only —
            # never the full message.
            await conn.execute(
                "INSERT INTO usage_logs (user_id, action, details) VALUES ($1,'message_sent',$2)",
                uid, json.dumps({"conversation_id": str(conv_id), "prompt_preview": _user_text[:80]}),
            )

    history.append({"role": "user", "content": req.prompt})

    ack = {
        "type": "conv_id",
        "conv_id": str(conv_id),
        # The user message is durably stored once this event is sent — the
        # client can clear the draft and mark the bubble "saved".
        "user_saved": True,
        "user_message_id": str(user_msg_id) if user_msg_id else None,
        "client_request_id": str(req_id) if req_id else None,
        "retry": is_retry,
    }

    if replay_text is not None:
        async def replay_stream():
            yield _sse(ack)
            yield _sse({"type": "delta", "text": replay_text})
            yield _sse({"type": "done", "replayed": True})
        return StreamingResponse(replay_stream(), media_type="text/event-stream",
                                 headers={"Cache-Control": "no-cache", "X-Accel-Buffering": "no"})

    async def event_stream():
        # The bulkhead slot is held for the whole stream — a StreamingResponse
        # returns from the handler immediately, so guarding only the handler
        # body would release the slot before any tokens flow.
        try:
            bulkhead_cm = bulkhead.acquire()
            await bulkhead_cm.__aenter__()
        except Exception:
            yield _sse({"type": "error", "code": "capacity", "retryable": True,
                        "message": "Server is at capacity — please retry shortly."})
            return
        full_text = ""
        saved = False
        try:
            yield _sse(ack)

            # P0 context budgeting — see app/core/ai/context/manager.py.
            budgeted_history = budget_history(history, model="claude-sonnet-4-6", max_tokens=2048)

            request_obj = CompletionRequest(
                messages=[Message(role=h["role"], content=h["content"]) for h in budgeted_history],
                model="claude-sonnet-4-6",
                max_tokens=2048,
                temperature=1.0,        # pinned to Anthropic's API default (see git history)
                conversation_id=None,   # chat.py owns its own conversations/messages tables,
                prompt_id=None,         # distinct from AIGateway's ai_conversations — do not
                memory_enabled=False,   # let the engine's history/memory enrichment touch
                tools=None,             # either.
                stream=True,
            )
            engine = InferenceEngine(pool=get_pool())
            total_tokens = 0
            stream_error: str | None = None

            async for chunk in engine.stream(
                request_obj, user_id=str(uid), org_id=None, auto_tools=False,
            ):
                ctype = chunk.get("type")
                if ctype == "delta":
                    text = chunk.get("text") or ""
                    if text:
                        full_text += text
                        yield _sse({"type": "delta", "text": text})
                elif ctype == "usage" and chunk.get("usage"):
                    total_tokens = chunk["usage"].get("total_tokens", 0)
                elif ctype == "error":
                    stream_error = chunk.get("error") or "Unknown AI provider error"
                    break

            if stream_error:
                log.warning("run_stream provider error conv=%s: %s", conv_id, stream_error)
                status = STATUS_PARTIAL if full_text else STATUS_FAILED
                with contextlib.suppress(Exception):
                    await _save_assistant(conv_id, req_id, full_text, status)
                    saved = True
                yield _sse({"type": "error", "message": stream_error, "retryable": True,
                            "partial": bool(full_text)})
                return

            if total_tokens:
                with contextlib.suppress(Exception):  # metering must never turn a success into an error
                    await record_org_tokens(org_id, total_tokens, str(conv_id))

            # Save assistant reply BEFORE sending `done` — the client stops
            # reading on `done`, so a disconnect could race the save otherwise.
            try:
                await _save_assistant(conv_id, req_id, full_text, STATUS_COMPLETE)
                saved = True
            except Exception as e:
                log.exception("run_stream: failed to save assistant message conv=%s", conv_id)
                yield _sse({"type": "error", "code": "save_failed", "retryable": True,
                            "message": "Failed to save reply: " + str(e)})
                return

            yield _sse({"type": "done"})

            # Best-effort telemetry after `done` — failures are silent.
            try:
                async with get_pool().acquire() as conn:
                    pid2 = await resolve_project_id(conn, req.project_id, uid)
                    run_id = await conn.fetchval(
                        "INSERT INTO agent_runs (project_id, agent_type, input_data, output_data, status, completed_at) "
                        "VALUES ($1,'claude',$2,$3,'completed',NOW()) RETURNING id",
                        pid2, json.dumps({"prompt": req.prompt}), json.dumps({"summary": full_text}),
                    )
                    await conn.execute(
                        "INSERT INTO usage_logs (user_id, action, details) VALUES ($1,'agent_run',$2)",
                        uid, json.dumps({"run_id": str(run_id), "prompt_preview": _user_text[:80]}),
                    )
            except Exception:
                pass

        except ContextBudgetError as e:
            log.warning("run_stream context budget rejected: %s", e)
            yield _sse({"type": "error", "code": "context_budget", "retryable": False,
                        "message": str(e)})
        except Exception as e:
            log.exception("run_stream error")
            yield _sse({"type": "error", "retryable": True, "message": str(e)})
        finally:
            # Client disconnected (or anything else) mid-stream: keep what
            # streamed, marked partial, so a reload shows an honest
            # "incomplete reply" instead of silently losing it. Shielded so
            # task cancellation doesn't abort the save itself.
            if not saved and full_text:
                with contextlib.suppress(BaseException):
                    await asyncio.shield(_save_assistant(conv_id, req_id, full_text, STATUS_PARTIAL))
            await bulkhead_cm.__aexit__(None, None, None)

    return StreamingResponse(event_stream(), media_type="text/event-stream",
                             headers={"Cache-Control": "no-cache", "X-Accel-Buffering": "no"})


@router.post("/api/run")
async def run_agent(req: RunRequest, request: Request):
    from app.core.reliability import get_bulkhead
    org_id = await check_org_quota(request)
    async with get_pool().acquire() as conn:
        uid = await owner_user_id(conn, request)

    request_obj = CompletionRequest(
        messages=[Message(role="user", content=req.prompt)],
        model="claude-sonnet-4-6",
        max_tokens=1024,
        temperature=1.0,  # match Anthropic's own API default — see run_stream's comment above
        conversation_id=None,
        prompt_id=None,
        memory_enabled=False,
        tools=None,
        stream=False,
    )
    engine = InferenceEngine(pool=get_pool())
    async with get_bulkhead("ai", 32).acquire():
        try:
            resp = await engine.complete(
                request_obj, user_id=str(uid), org_id=None, auto_tools=False,
            )
        except anthropic.AuthenticationError:
            raise HTTPException(401, "Invalid Anthropic API key.") from None
        except anthropic.BadRequestError as e:
            raise HTTPException(402, anthropic_error_message(e)) from None
        except RuntimeError as e:
            raise HTTPException(503, str(e)) from None
        except Exception as e:
            raise HTTPException(502, str(e)) from None

    await record_org_tokens(org_id, resp.usage.total_tokens, req.project_id)
    summary = resp.content
    async with get_pool().acquire() as conn:
        pid = await resolve_project_id(conn, req.project_id, uid)
        run_id = await conn.fetchval(
            "INSERT INTO agent_runs (project_id, agent_type, input_data, output_data, status, completed_at) "
            "VALUES ($1,'claude',$2,$3,'completed',NOW()) RETURNING id",
            pid, json.dumps({"prompt": req.prompt}), json.dumps({"summary": summary}),
        )
        await conn.execute(
            "INSERT INTO usage_logs (user_id, action, details) VALUES ($1,'agent_run',$2)",
            uid, json.dumps({"run_id": str(run_id), "prompt_preview": req.prompt[:80]}),
        )
    return {"result": {"summary": summary}}


def _conv_out(r) -> dict:
    return {
        "id": str(r["id"]),
        "title": r["title"],
        "project_id": str(r["project_id"]),
        "archived": r["archived_at"] is not None,
        "created_at": r["created_at"].isoformat(),
        "updated_at": r["updated_at"].isoformat(),
    }


_CONV_COLS = "c.id, c.title, c.project_id, c.archived_at, c.created_at, c.updated_at"


